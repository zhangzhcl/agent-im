import { createInterface } from 'node:readline';
import { createRequire } from 'node:module';

// serverInfo 版本跟随 package.json，避免升级后 MCP 客户端仍显示旧版本
const require = createRequire(import.meta.url);
const pkgVersion = require('../../package.json').version;

/**
 * Model Context Protocol (MCP) server for Claude Desktop, Cursor, and ChatGPT Desktop.
 */
export class McpAgentServer {
  constructor({ onSendMessage, onSendFile, onGetHistory } = {}) {
    this.onSendMessage = onSendMessage;
    this.onSendFile = onSendFile;
    this.onGetHistory = onGetHistory;
  }

  async handleJsonRpc(request) {
    if (!request || request.jsonrpc !== '2.0') {
      return {
        jsonrpc: '2.0',
        id: request?.id ?? null,
        error: { code: -32600, message: 'Invalid Request' },
      };
    }

    const { id, method, params } = request;

    // 1. MCP Lifecycle Handshake: initialize
    if (method === 'initialize') {
      return {
        jsonrpc: '2.0',
        id,
        result: {
          protocolVersion: params?.protocolVersion || '2024-11-05',
          capabilities: {
            tools: {
              listChanged: false,
            },
          },
          serverInfo: {
            name: 'omni-im-gateway',
            version: pkgVersion,
          },
        },
      };
    }

    // 2. Client initialized notification (no response needed according to JSON-RPC notifications, or empty ack)
    if (method === 'notifications/initialized' || method === 'initialized') {
      return null;
    }

    // 3. Ping keepalive
    if (method === 'ping') {
      return {
        jsonrpc: '2.0',
        id,
        result: {},
      };
    }

    if (method === 'tools/list') {
      return {
        jsonrpc: '2.0',
        id,
        result: {
          tools: [
            {
              name: 'send_im_message',
              description: 'Send a text or markdown message to an IM chat or group target',
              inputSchema: {
                type: 'object',
                properties: {
                  target: { type: 'string', description: 'Target chat alias or conversation identifier' },
                  text: { type: 'string', description: 'Message text content' },
                  format: { type: 'string', enum: ['plain', 'markdown'], description: 'Text format' },
                },
                required: ['target', 'text'],
              },
            },
            {
              name: 'send_im_file',
              description: 'Send a file or image generated by the agent to an IM chat or group',
              inputSchema: {
                type: 'object',
                properties: {
                  target: { type: 'string', description: 'Target chat alias or conversation identifier' },
                  filePath: { type: 'string', description: 'Local path of the file to send' },
                },
                required: ['target', 'filePath'],
              },
            },
            {
              name: 'get_im_history',
              description: 'Retrieve recent conversation history from an IM chat',
              inputSchema: {
                type: 'object',
                properties: {
                  target: { type: 'string', description: 'Target chat alias or conversation identifier' },
                  limit: { type: 'integer', minimum: 1, maximum: 50, description: 'Number of messages to retrieve' },
                },
                required: ['target'],
              },
            },
          ],
        },
      };
    }

    if (method === 'tools/call') {
      const toolName = params?.name;
      const args = params?.arguments || {};

      try {
        let output = null;
        if (toolName === 'send_im_message') {
          output = await this.onSendMessage(args.target, args.text, args.format);
        } else if (toolName === 'send_im_file') {
          output = await this.onSendFile(args.target, args.filePath);
        } else if (toolName === 'get_im_history') {
          output = await this.onGetHistory(args.target, args.limit);
        } else {
          return {
            jsonrpc: '2.0',
            id,
            error: { code: -32601, message: `Tool not found: ${toolName}` },
          };
        }

        return {
          jsonrpc: '2.0',
          id,
          result: {
            content: [
              {
                type: 'text',
                text: typeof output === 'string' ? output : JSON.stringify(output),
              },
            ],
          },
        };
      } catch (err) {
        return {
          jsonrpc: '2.0',
          id,
          error: { code: -32000, message: err?.message || 'Tool execution failed' },
        };
      }
    }

    return {
      jsonrpc: '2.0',
      id,
      error: { code: -32601, message: `Method not found: ${method}` },
    };
  }

  startStdio() {
    const rl = createInterface({
      input: process.stdin,
      crlfDelay: Infinity,
    });

    rl.on('line', async (line) => {
      const trimmed = line.trim();
      if (!trimmed) return;
      try {
        const req = JSON.parse(trimmed);
        const res = await this.handleJsonRpc(req);
        if (res !== null && res !== undefined) {
          process.stdout.write(JSON.stringify(res) + '\n');
        }
      } catch {
        process.stdout.write(
          JSON.stringify({
            jsonrpc: '2.0',
            id: null,
            error: { code: -32700, message: 'Parse error' },
          }) + '\n'
        );
      }
    });
  }
}
